import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const mk = async (name) => {
  const p = await browser.newPage();
  p.on('pageerror', (e) => console.log(`[${name} pageerror]`, String(e).slice(0, 300)));
  p.on('console', (m) => { if (m.type() === 'error') console.log(`[${name} console.error]`, m.text().slice(0, 200)); });
  await p.goto('http://127.0.0.1:5173');
  await p.waitForTimeout(1200);
  await p.getByTestId('nickname').fill(name);
  return p;
};
const a = await mk('甲');
await a.getByTestId('create').click();
await a.waitForTimeout(800);
const code = ((await a.getByTestId('room-code').textContent()) ?? '').trim();
const b = await mk('乙');
await b.getByTestId('code').fill(code);
await b.getByTestId('join').click();
await b.waitForTimeout(1000);
await a.getByTestId('ready').click();
await b.getByTestId('ready').click();
await a.waitForTimeout(9000);
console.log('--- 乙点击离开 ---');
await b.getByTestId('leave').click();
await b.waitForTimeout(2500);
console.log('乙页面顶部文字:', JSON.stringify((await b.locator('body').innerText()).slice(0, 120)));
await a.waitForTimeout(2500);
const bodyText = (await a.locator('body').innerText()).trim();
console.log('甲页面内容长度:', bodyText.length);
console.log('甲页面内容:', JSON.stringify(bodyText.slice(0, 200)));
await a.screenshot({ path: 'leave-after.png' });
await browser.close();
console.log('done');
